#!/usr/bin/env python3
"""Identifiers of the formal supplement's primary-identifier table (LEANREPO M4, 2026-10-19).

    python scripts/map_identifiers.py            # rewrite docs/census/map-identifiers.txt and scripts/map_scan.lean
    python scripts/map_identifiers.py --check    # fail if either file is out of date with the map

Reads the longtable "Headline results and their primary Lean identifiers" in
paper/appendix_sections/07_formalization_map.tex and collects every Lean identifier the table
names, rejoining identifiers the typesetting splits (a `\\path{..._}` or a namespace prefix ending in a dot,
continued after a line break, or a Greek letter set in math between two pieces). `scripts/map_scan.lean`, elaborated by the HPC
job after the build, checks that each identifier names a declaration of the compiled environment
(by its last name component, as `checkdecls` does for a blueprint). The check proves existence
only: types, proofs and the correspondence to the paper's sentences are checked elsewhere (the
headline snapshot, the axiom scans, the reviewed map)."""
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
MAP = REPO / "paper/appendix_sections/07_formalization_map.tex"
LIST = REPO / "docs/census/map-identifiers.txt"
SCAN = REPO / "scripts/map_scan.lean"
GREEK = {"alpha": "α", "beta": "β", "gamma": "γ", "delta": "δ", "sigma": "σ", "tau": "τ", "eta": "η",
         "mu": "μ", "theta": "θ", "lambda": "λ", "rho": "ρ", "pi": "π", "ell": "ℓ", "kappa": "κ"}
IDENT = re.compile(r"^[A-Za-z_][\w'.₀-₉αβγδσστημθλρπℓκ]*$")


def table_text() -> str:
    t = MAP.read_text(encoding="utf-8-sig")
    t = "\n".join(l for l in t.split("\n") if not l.lstrip().startswith("%"))
    i = t.index("Headline results and their primary Lean identifiers")
    j = t.index(r"\end{longtable}", i)
    return t[i:j]


def identifiers() -> list[str]:
    out = []
    body = table_text().split(r"\endlastfoot", 1)[-1]
    for row in body.split("\\\\"):
        if "&" not in row:
            continue
        cell = row.split("&", 1)[1].replace(r"\_", "_")
        cell = re.sub(r"\$\\([a-zA-Z]+)\$", lambda m: "\x00G" + GREEK.get(m[1], "?") + "\x00", cell)
        items = []
        for m in re.finditer(r"\\(?:path|texttt)\{([^}]*)\}|\x00G(.)\x00|(\\newline|\s+)|([^\\\x00\s]+|\\[a-zA-Z]+)", cell):
            if m[1] is not None:
                items.append(("id", m[1]))
            elif m[2] is not None:
                items.append(("greek", m[2]))
            elif m[3] is not None:
                items.append(("space", ""))
            else:
                items.append(("other", m[4]))
        collapsed = []
        for it in items:  # a line break and the whitespace after it are one gap
            if it[0] == "space" and collapsed and collapsed[-1][0] == "space":
                continue
            collapsed.append(it)
        items = collapsed
        merged = []
        k = 0
        while k < len(items):
            kind, text = items[k]
            if kind != "id":
                merged.append(items[k]); k += 1; continue
            cur = text
            while True:
                if (k + 2 < len(items) and items[k + 1][0] == "greek" and items[k + 2][0] == "id"):
                    cur += items[k + 1][1] + items[k + 2][1]; k += 2; continue
                if (cur.endswith(("_", ".")) and k + 2 < len(items) and items[k + 1][0] == "space"
                        and items[k + 2][0] == "id"):
                    cur += items[k + 2][1]; k += 2; continue
                break
            merged.append(("id", cur)); k += 1
        for kind, text in merged:
            if kind == "id":
                for tok in re.split(r"[\s,;]+", text):
                    tok = tok.strip().rstrip(".")
                    if tok and IDENT.match(tok) and tok not in out:
                        out.append(tok)
    return out


def render(ids: list[str]) -> tuple[str, str]:
    lst = ("# Lean identifiers named by the formal supplement's primary-identifier table\n"
           "# (paper/appendix_sections/07_formalization_map.tex). Generated by scripts/map_identifiers.py;\n"
           "# checked against the compiled environment by scripts/map_scan.lean in the HPC job.\n"
           + "".join(i + "\n" for i in ids))
    body = ",\n".join("  " + '"' + i.replace("\\", "\\\\").replace('"', '\\"') + '"' for i in ids)
    lean = f"""import Sanctions

/-! Map-identifier scan (LEANREPO M4). Generated by `scripts/map_identifiers.py` from the formal
supplement's primary-identifier table; do not edit by hand. Each identifier must be the last name
component of a declaration in the compiled environment. Existence only, as `checkdecls` checks a
blueprint: types, proofs and correspondence are checked by the snapshot, the axiom scans and the
reviewed map. -/

open Lean Elab Command

/-- The identifiers the primary-identifier table names. -/
def mapIdentifiers : List String := [
{body}
]

/-- The last name component of `n` as a string. -/
def mapLastComponent : Name → String
  | .str _ s => s
  | .num p _ => mapLastComponent p
  | .anonymous => ""

#eval show CommandElabM Unit from do
  let env ← getEnv
  let lasts : Std.HashSet String :=
    env.constants.fold (fun acc n _ => acc.insert (mapLastComponent n)) {{}}
  let mut missing : Array String := #[]
  for i in mapIdentifiers do
    let last := (i.splitOn ".").getLast!
    unless lasts.contains last do
      missing := missing.push i
  for i in missing do
    logInfo m!"MAP-MISSING {{i}}"
  logInfo m!"MAP-CHECK identifiers={{mapIdentifiers.length}} missing={{missing.size}}"
  unless missing.isEmpty do
    throwError "map identifiers missing from the compiled environment: {{missing.size}}"
"""
    return lst, lean


def main() -> None:
    ids = identifiers()
    lst, lean = render(ids)
    if "--check" in sys.argv:
        stale = [p.name for p, want in ((LIST, lst), (SCAN, lean))
                 if not p.is_file() or p.read_text(encoding="utf-8") != want]
        if stale:
            sys.exit("map identifiers out of date (run scripts/map_identifiers.py): " + ", ".join(stale))
        print(f"map identifiers current: {len(ids)}")
        return
    LIST.write_text(lst, encoding="utf-8", newline="\n")
    SCAN.write_text(lean, encoding="utf-8", newline="\n")
    print(f"wrote {len(ids)} identifiers to {LIST.relative_to(REPO)} and {SCAN.relative_to(REPO)}")


if __name__ == "__main__":
    main()
